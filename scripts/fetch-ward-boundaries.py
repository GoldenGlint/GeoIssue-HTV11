"""Regenerates src/ward-boundaries.js from the City of Toronto "City Wards" open dataset.

Downloads the 25-ward boundaries (WGS84 GeoJSON), simplifies each ring, and writes a small ES module
the frontend imports to assign wards (point-in-polygon) and draw ward outlines.

Usage:  python scripts/fetch-ward-boundaries.py
Data:   Contains information licensed under the Open Government Licence – Toronto.
        https://open.toronto.ca/dataset/city-wards/
"""
import datetime, json, math, pathlib, urllib.request

PACKAGE = "https://ckan0.cf.opendata.inter.prod-toronto.ca/api/3/action/package_show?id=city-wards"
RESOURCE_NAME = "City Wards Data - 4326.geojson"
HEADERS = {"User-Agent": "GeoIssue-HTV-prototype/0.1 (hackathon demo)"}
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "ward-boundaries.js"


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=120) as response:
        return response.read()


def simplify(ring, tolerance_m=15):
    """Ramer–Douglas–Peucker in a local metric plane; keeps the ring closed."""
    if len(ring) < 5:
        return ring
    k = math.cos(math.radians(ring[0][1]))
    xy = [(lng * 111320 * k, lat * 110540) for lng, lat in ring]

    def rdp(start, end):
        (ax, ay), (bx, by) = xy[start], xy[end]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy) or 1
        best, index = 0, None
        for i in range(start + 1, end):
            d = abs(dy * (xy[i][0] - ax) - dx * (xy[i][1] - ay)) / length if length > 1 else math.hypot(xy[i][0] - ax, xy[i][1] - ay)
            if d > best:
                best, index = d, i
        if index is None or best <= tolerance_m:
            return [start, end]
        return rdp(start, index)[:-1] + rdp(index, end)

    # Split at the farthest point so the closed ring's start/end don't collapse it.
    far = max(range(len(xy)), key=lambda i: math.hypot(xy[i][0] - xy[0][0], xy[i][1] - xy[0][1]))
    keep = rdp(0, far)[:-1] + rdp(far, len(ring) - 1)
    return [ring[i] for i in keep]


def main():
    package = json.loads(get(PACKAGE))["result"]
    resource = next(r for r in package["resources"] if r["name"] == RESOURCE_NAME)
    features = json.loads(get(resource["url"]))["features"]
    wards, points = [], 0
    for feature in sorted(features, key=lambda f: int(f["properties"]["AREA_SHORT_CODE"])):
        props, geometry = feature["properties"], feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        rings = [[[round(x, 5), round(y, 5)] for x, y in simplify([p[:2] for p in ring])] for polygon in polygons for ring in polygon]
        points += sum(len(r) for r in rings)
        # Each polygon keeps its outer ring first, then holes; point-in-polygon uses even-odd over all rings.
        wards.append({"id": str(int(props["AREA_SHORT_CODE"])), "name": props["AREA_NAME"], "rings": rings})
    rows = ",\n  ".join(json.dumps(w, ensure_ascii=False, separators=(",", ":")) for w in wards)
    OUT.write_text(
        f"// Generated by scripts/fetch-ward-boundaries.py on {datetime.date.today()} from the City of Toronto \"City Wards\" dataset\n"
        f"// (last refreshed {package.get('last_refreshed', 'unknown')[:10]}). Do not edit by hand.\n"
        "// Contains information licensed under the Open Government Licence – Toronto.\n"
        "// { id, name, rings: [[lng, lat], ...][] } with outer rings and holes; test points with the even-odd rule.\n"
        f"export const wardBoundaries = [\n  {rows},\n];\n",
        encoding="utf-8",
    )
    print(f"{len(wards)} wards, {points} points -> {OUT}")


if __name__ == "__main__":
    main()
