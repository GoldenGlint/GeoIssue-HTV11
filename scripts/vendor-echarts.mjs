// Regenerates src/vendor/echarts.js: a trimmed Apache ECharts build (https://echarts.apache.org, Apache-2.0) at a
// pinned version, holding only the charts the dashboard draws, so the app keeps no runtime dependency or CDN.
// To use another chart or component: add it to the entry below and run `node scripts/vendor-echarts.mjs`.
import { execSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '6.1.0', ESBUILD = '0.25.10';
const entry = `export * from 'echarts/core';
import { use } from 'echarts/core';
import { LineChart, BarChart, PieChart } from 'echarts/charts';
import { GridComponent, TooltipComponent } from 'echarts/components';
import { LabelLayout } from 'echarts/features';
import { SVGRenderer } from 'echarts/renderers';
use([LineChart, BarChart, PieChart, GridComponent, TooltipComponent, LabelLayout, SVGRenderer]);
`;
const banner = `/*! Apache ECharts ${VERSION} (https://echarts.apache.org), Apache License 2.0, with ZRender (BSD-3-Clause) and tslib (0BSD).
 * Trimmed build generated by scripts/vendor-echarts.mjs: line, bar and pie charts, grid, tooltip, label layout, SVG renderer. */`;

const dir = mkdtempSync(join(tmpdir(), 'geoissue-echarts-'));
const out = fileURLToPath(new URL('../src/vendor/echarts.js', import.meta.url));
try {
  writeFileSync(join(dir, 'package.json'), '{"private":true,"type":"module"}');
  writeFileSync(join(dir, 'entry.js'), entry);
  // The build runs in its own process so esbuild's binary has exited (and unlocked the folder on Windows) before cleanup.
  writeFileSync(join(dir, 'build.js'), `import { build } from 'esbuild';
await build({ entryPoints: ['entry.js'], outfile: ${JSON.stringify(out)}, bundle: true, format: 'esm', minify: true, target: 'es2020',
  legalComments: 'none', banner: { js: ${JSON.stringify(banner)} } });`);
  execSync(`npm install --no-audit --no-fund --silent echarts@${VERSION} esbuild@${ESBUILD}`, { cwd: dir, stdio: 'inherit' });
  execSync('node build.js', { cwd: dir, stdio: 'inherit' });
  console.log(`Wrote ECharts ${VERSION} to src/vendor/echarts.js (${Math.round(statSync(out).size / 1024)} KB)`);
} finally { rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 300 }); }
