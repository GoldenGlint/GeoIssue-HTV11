// Exports the frontend's neighbourhoods, wards and infrastructure (src/data.js) as the analysis reference
// data, so analyzed issues carry the same neighbourhood, ward and asset IDs as the map.
// Run after changing them in src/data.js: node scripts/export-analysis-reference.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { neighbourhoods, wards, infrastructure } from '../src/data.js';

const out = new URL('../analysis/refdata/toronto/', import.meta.url);
const note = 'Generated by scripts/export-analysis-reference.mjs from src/data.js. Neighbourhoods are sample street corners and each has one approximate ward, so area assignment is approximate.';

// Street type and direction words dropped when matching corners in text: "King St W & Spadina Ave" -> ["king", "spadina"].
const suffixes = new Set(['st', 'ave', 'rd', 'dr', 'blvd', 'cres', 'crt', 'ct', 'pl', 'ln', 'way', 'trail', 'pkwy', 'e', 'w', 'n', 's']);
const streetWords = street => {
  const words = street.toLowerCase().replace(/’/g, "'").replace(/[^a-z0-9' ]/g, ' ').split(/\s+/).filter(Boolean);
  while (words.length > 1 && suffixes.has(words.at(-1))) words.pop();
  if (words.length > 1 && words[0] === 'the') words.shift();
  return words.join(' ');
};

const corners = neighbourhoods.flatMap(n => n.places.map(([address, lng, lat]) => ({ n, address, lng, lat })));
const feature = (geometry, properties) => ({ type: 'Feature', properties, geometry });

const files = {
  'neighbourhoods.geojson': {
    type: 'FeatureCollection', placeholder: true, note,
    features: corners.map(({ n, address, lng, lat }) => feature({ type: 'Point', coordinates: [lng, lat] },
      { neighbourhood_id: n.id, neighbourhood_name: n.name, ward_id: n.ward, ward_name: wards[n.ward], corner: address })),
  },
  'infrastructure.geojson': {
    type: 'FeatureCollection', note: 'TTC stations and major roads from OpenStreetMap (© OpenStreetMap contributors, ODbL); schools are approximate samples.',
    features: infrastructure.map(a => feature(a.geometry, { asset_id: a.asset_id, type: a.type, name: a.name })),
  },
  'places.json': {
    placeholder: true, note,
    places: corners.map(({ address, lng, lat }) => ({ name: address, kind: 'intersection', match_all: address.split(' & ').map(streetWords), lng, lat, radius_m: 75 })),
  },
};

await mkdir(out, { recursive: true });
for (const [name, data] of Object.entries(files)) await writeFile(new URL(name, out), JSON.stringify(data, null, 1) + '\n');
console.log(`Wrote ${corners.length} corners in ${neighbourhoods.length} neighbourhoods and ${infrastructure.length} assets to analysis/refdata/toronto/`);
