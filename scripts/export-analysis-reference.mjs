// Exports the frontend's neighbourhoods, wards and infrastructure (src/data.js) as the analysis reference
// data, so analyzed issues carry the same neighbourhood, ward and asset IDs as the map. The OpenStreetMap
// gazetteer next to these files (osm-places.json) comes from scripts/fetch-osm-places.py instead.
// Run after changing them in src/data.js: node scripts/export-analysis-reference.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { neighbourhoods, wards, wardBoundaries, infrastructure } from '../src/data.js';

const out = new URL('../analysis/refdata/toronto/', import.meta.url);
const note = 'Generated by scripts/export-analysis-reference.mjs from src/data.js. Neighbourhoods are sample street corners, so neighbourhood assignment is approximate.';

// Street type and direction words dropped when matching corners in text: "King St W & Spadina Ave" -> ["king", "spadina"].
// The two names must appear together, as in "King and Spadina" or "King St W / Spadina".
const suffixes = new Set(['st', 'ave', 'rd', 'dr', 'blvd', 'cres', 'crt', 'ct', 'pl', 'ln', 'way', 'trail', 'pkwy', 'e', 'w', 'n', 's']);
const streetWords = street => {
  const words = street.toLowerCase().replace(/’/g, "'").replace(/[^a-z0-9' ]/g, ' ').split(/\s+/).filter(Boolean);
  while (words.length > 1 && suffixes.has(words.at(-1))) words.pop();
  if (words.length > 1 && words[0] === 'the') words.shift();
  return words.join(' ');
};

const corners = neighbourhoods.flatMap(n => n.places.map(([address, lng, lat]) => ({ n, address, lng, lat })));
const feature = (geometry, properties) => ({ type: 'Feature', properties, geometry });

const files = {
  // The City's ward boundaries, as the map draws them, named as in the app. Every ward is a single ring.
  'wards.geojson': {
    type: 'FeatureCollection', note: 'City of Toronto "City Wards" (Open Government Licence – Toronto), from src/ward-boundaries.js.',
    features: wardBoundaries.map(w => feature({ type: 'Polygon', coordinates: w.rings }, { ward_id: w.id, ward_name: wards[w.id] })),
  },
  'neighbourhoods.geojson': {
    type: 'FeatureCollection', placeholder: true, note,
    features: corners.map(({ n, address, lng, lat }) => feature({ type: 'Point', coordinates: [lng, lat] },
      { neighbourhood_id: n.id, neighbourhood_name: n.name, ward_id: n.ward, ward_name: wards[n.ward], corner: address })),
  },
  'infrastructure.geojson': {
    type: 'FeatureCollection', note: 'TTC stations and major roads from OpenStreetMap (© OpenStreetMap contributors, ODbL); schools are approximate samples.',
    features: infrastructure.map(a => feature(a.geometry, { asset_id: a.asset_id, type: a.type, name: a.name })),
  },
  'places.json': {
    placeholder: true, note,
    places: [
      ...corners.map(({ address, lng, lat }) => ({ name: address, kind: 'intersection', streets: address.split(' & ').map(streetWords), lng, lat, radius_m: 75 })),
      // TTC stations match only as the whole name ("Queen Station"), so "Queen Street ... near the station" does not.
      ...infrastructure.filter(a => a.type === 'TTC' && a.geometry.type === 'Point').map(a => ({ name: a.name, kind: 'landmark', aliases: [a.name], lng: a.geometry.coordinates[0], lat: a.geometry.coordinates[1], radius_m: 150 })),
    ],
  },
};

await mkdir(out, { recursive: true });
for (const [name, data] of Object.entries(files)) await writeFile(new URL(name, out), JSON.stringify(data, null, 1) + '\n');
console.log(`Wrote ${wardBoundaries.length} wards, ${corners.length} corners in ${neighbourhoods.length} neighbourhoods and ${infrastructure.length} assets to analysis/refdata/toronto/`);
