"""Regenerates src/osm-infrastructure.js from OpenStreetMap via the Overpass API.

Fetches TTC subway / LRT station positions and the geometry of four major roads
(Gardiner Expressway, Don Valley Parkway, Highway 401, Lake Shore Boulevard),
simplifies the lines, and writes a small ES module the frontend imports.

Usage:  python scripts/fetch-osm-infrastructure.py
Data:   © OpenStreetMap contributors, ODbL 1.0 — https://www.openstreetmap.org/copyright
"""
import datetime, json, math, pathlib, urllib.parse, urllib.request

BBOX = "43.58,-79.64,43.86,-79.11"  # south, west, north, east: City of Toronto
QUERY = f"""
[out:json][timeout:90];
(
  way["highway"="motorway"]["name"~"^(Gardiner Expressway|Don Valley Parkway)$"]({BBOX});
  way["highway"="motorway"]["ref"~"(^|;)401($|;)"]({BBOX});
  way["highway"~"^(trunk|primary|secondary)$"]["name"~"^Lake Shore Boulevard (East|West)$"]({BBOX});
  node["railway"="station"]["station"~"^(subway|light_rail)$"]["network"~"TTC|Toronto Transit Commission"]({BBOX});
  node["railway"="station"]["station"~"^(subway|light_rail)$"]["operator"~"TTC|Toronto Transit Commission"]({BBOX});
);
out geom;
"""
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "osm-infrastructure.js"


def road_name(tags):
    name = tags.get("name", "")
    if "401" in tags.get("ref", "").split(";") or "401" in name:
        return "Highway 401"
    if name.startswith("Lake Shore Boulevard"):
        return "Lake Shore Boulevard"
    return name


def simplify(points, tolerance_m=25):
    """Ramer–Douglas–Peucker in a local metric plane."""
    if len(points) < 3:
        return points
    lat0 = points[0][1]
    k = math.cos(math.radians(lat0))
    xy = [((lng * 111320 * k), (lat * 110540)) for lng, lat in points]

    def rdp(start, end):
        (ax, ay), (bx, by) = xy[start], xy[end]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy) or 1
        best, index = 0, None
        for i in range(start + 1, end):
            d = abs(dy * (xy[i][0] - ax) - dx * (xy[i][1] - ay)) / length
            if d > best:
                best, index = d, i
        if index is None or best <= tolerance_m:
            return [start, end]
        return rdp(start, index)[:-1] + rdp(index, end)

    return [points[i] for i in rdp(0, len(points) - 1)]


def main():
    request = urllib.request.Request(
        "https://overpass-api.de/api/interpreter",
        data=urllib.parse.urlencode({"data": QUERY}).encode(),
        headers={"User-Agent": "GeoIssue-HTV-prototype/0.1 (hackathon demo)"},
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        elements = json.load(response)["elements"]

    stations, roads = {}, {}
    for el in elements:
        tags = el.get("tags", {})
        if el["type"] == "node":
            name = tags.get("name", "").strip()
            if name and name not in stations:
                stations[name] = [round(el["lon"], 5), round(el["lat"], 5)]
        elif el["type"] == "way" and el.get("geometry"):
            line = simplify([[g["lon"], g["lat"]] for g in el["geometry"]])
            roads.setdefault(road_name(tags), []).append([[round(x, 5), round(y, 5)] for x, y in line])

    station_rows = ",\n  ".join(json.dumps([n if n.endswith("Station") else f"{n} Station", *c], ensure_ascii=False) for n, c in sorted(stations.items()))
    road_rows = ",\n  ".join(f"{json.dumps(name)}: {json.dumps(lines, separators=(',', ':'))}" for name, lines in sorted(roads.items()))
    OUT.write_text(
        f"// Generated by scripts/fetch-osm-infrastructure.py on {datetime.date.today()}. Do not edit by hand.\n"
        "// © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).\n"
        "// [name, lng, lat] for TTC subway and LRT stations.\n"
        f"export const osmStations = [\n  {station_rows},\n];\n"
        "// Road name → simplified line segments ([lng, lat] points).\n"
        f"export const osmRoads = {{\n  {road_rows},\n}};\n",
        encoding="utf-8",
    )
    points = sum(len(line) for lines in roads.values() for line in lines)
    print(f"{len(stations)} stations, {len(roads)} roads, {sum(len(v) for v in roads.values())} segments, {points} points -> {OUT}")


if __name__ == "__main__":
    main()
