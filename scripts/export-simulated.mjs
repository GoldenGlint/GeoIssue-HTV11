// Exports the fictional sample issues (src/data.js) as data/simulated/issues.json, the source of the
// "Simulated" dataset in Tiger Data. Each gets a sample photo of its category (assets/evidence), which
// illustrates the category, not the record. Run after changing the sample generator, then reload Tiger Data:
//   node scripts/export-simulated.mjs && python -m analysis.tiger simulate
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { sampleIssues, DEMO_DATE } from '../src/data.js';

const credits = JSON.parse(await readFile(new URL('../assets/evidence/credits.json', import.meta.url), 'utf8'));
const photos = {};
for (const credit of credits) (photos[credit.category] ||= []).push(credit);

const issues = sampleIssues();
for (const [j, issue] of issues.entries()) {
  const options = photos[issue.issue_type];
  if (!options?.length) continue;
  const photo = options[j % options.length];
  issue.evidence_thumbnail = `./assets/evidence/${photo.file}`;
  issue.evidence_credit = { title: photo.title, author: photo.author, license: photo.license, license_url: photo.license_url, source_url: photo.source_url, is_sample: true };
}

const out = new URL('../data/simulated/', import.meta.url);
await mkdir(out, { recursive: true });
const note = 'Generated by scripts/export-simulated.mjs from src/data.js. Fictional issues; times are moved forward when loaded into Tiger Data.';
await writeFile(new URL('issues.json', out), `${JSON.stringify({ note, generated_at: DEMO_DATE, issues })}\n`);
console.log(`Wrote ${issues.length} simulated issues to data/simulated/issues.json`);
