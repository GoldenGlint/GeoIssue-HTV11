// Regenerates src/icons.js from Lucide (https://lucide.dev, ISC licence) at a pinned version, so the app keeps
// one consistent icon set with no runtime dependency. To add an icon: add `appName: 'lucide-name'` below and run
// `node scripts/vendor-icons.mjs`. Browse names at https://lucide.dev/icons.
import { writeFile } from 'node:fs/promises';

const VERSION = '1.51.0';
const names = {
  // Navigation and page chrome
  map: 'map', database: 'database', chart: 'chart-column', bookmark: 'bookmark', clock: 'clock', shield: 'shield-check',
  settings: 'settings', help: 'circle-question-mark', sun: 'sun', moon: 'moon', plus: 'plus', minus: 'minus',
  // Actions
  search: 'search', tag: 'tag', funnel: 'funnel', refresh: 'rotate-ccw', upload: 'upload', download: 'download',
  close: 'x', arrow: 'arrow-right', back: 'arrow-left', external: 'external-link', share: 'share-2', copy: 'copy',
  edit: 'pencil', check: 'check', code: 'code', image: 'image', sparkles: 'sparkles', info: 'info', lightbulb: 'lightbulb',
  columns: 'columns-3', chevron: 'chevron-down',
  // Map tools
  pin: 'map-pin', density: 'flame', layers: 'layers', hand: 'hand', select: 'square-dashed-mouse-pointer', fit: 'maximize',
  home: 'house', target: 'crosshair', locate: 'locate-fixed', person: 'person-standing', route: 'route', leaf: 'leaf',
  // Issue categories (src/data.js) and severity
  barrier: 'construction', footprints: 'footprints', spray: 'spray-can', trash: 'trash-2', water: 'waves', shapes: 'shapes',
  warning: 'triangle-alert',
  // Infrastructure layers and wards
  train: 'train-front', school: 'school', road: 'road', ballot: 'vote',
};

const glyph = async name => {
  const response = await fetch(`https://unpkg.com/lucide-static@${VERSION}/icons/${name}.svg`);
  if (!response.ok) throw new Error(`Lucide has no icon "${name}" (HTTP ${response.status})`);
  // Keep only the drawing inside <svg>…</svg>, on one line.
  return (await response.text()).replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').replaceAll("'", '&#39;');
};
const entries = await Promise.all(Object.entries(names).map(async ([key, name]) => `  ${/^[a-z]+$/.test(key) ? key : `'${key}'`}: '${await glyph(name)}', // ${name}`));
await writeFile(new URL('../src/icons.js', import.meta.url), `// Lucide icons v${VERSION} (https://lucide.dev), ISC licence © Lucide Contributors. Generated by
// scripts/vendor-icons.mjs; edit the list there and rerun rather than editing this file. Unknown names fall back to the pin.
const glyphs = {
${entries.join('\n')}
};
export const icon = (name, cls = '') => \`<svg class="icon \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${glyphs[name] || glyphs.pin}</svg>\`;
`);
console.log(`Wrote ${entries.length} Lucide v${VERSION} icons to src/icons.js`);
